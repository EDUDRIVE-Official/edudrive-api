import assert from 'node:assert/strict';
import { registerPassengerPreview } from '../resources/js/passenger-preview-controller.js';
let create;
registerPassengerPreview({data(name, factory) { create = factory; }});
globalThis.window = {matchMedia: () => ({matches: false})};
const events = [];
const choices = [{id:'segura', correct:true}, {id:'impulso', correct:false}];
const practice = create(choices, 'moving', 'block-original');
practice.$dispatch = (name, detail) => events.push({name, ...detail});
practice.choose('segura');
assert.equal(practice.selected.id, 'segura');
assert.deepEqual(events.at(-1), {name:'scenario-answered', id:'block-original', correct:true});
practice.retry();
assert.equal(practice.selected, null);
assert.equal(events.at(-1).correct, false);
practice.choose('impulso');
assert.equal(events.at(-1).correct, false);
practice.choose('missing');
assert.equal(events.length, 3);
console.log('Passenger completion: original IDs, correct/wrong answers and retry verified.');
